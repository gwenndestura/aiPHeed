"""Write docs/fi6/RESULTS.md from data/fi6 outputs (no hand-typed numbers).   python -m app.fi6.report"""
from __future__ import annotations

import json

import pandas as pd

from app.fi5.paths import BACKEND_DIR
from app.fi6.evaluate import BASELINES, PROPOSED, SPECS
from app.fi6.paths import OUT, VALIDATION

DOCS = BACKEND_DIR.parent / "docs" / "fi6"


def _f(x):
    if x is None or (isinstance(x, float) and pd.isna(x)):
        return "n/a"
    if isinstance(x, list):
        return "[" + ", ".join(f"{v:.2f}" for v in x) + "]"
    return f"{x:.3f}" if isinstance(x, float) else str(x)


def _t(rows, cols):
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] +
                     ["| " + " | ".join(_f(r.get(c)) for c in cols) + " |" for r in rows])


def build() -> str:
    ev = json.loads((OUT / "evaluation.json").read_text())
    fc = json.loads((OUT / "forecast.json").read_text())
    ver = json.loads((OUT / "verification.json").read_text())
    lock = json.loads((OUT / "METHOD_LOCK.json").read_text())
    S = ev["summary"]
    md = ["# FI6 results (generated by `python -m app.fi6.report`)", "",
          f"Lock `{lock['lock_sha256'][:16]}`, code matches lock: **{ev['lock']['code_matches_lock']}**. "
          f"Furthest reliable lead: **{ev['max_reliable_lead']}**.", "",
          "## Proposed LightGBM (change model), walk-forward 2010-Q1..2026-Q3", ""]
    cols = ["n", "n_high", "accuracy", "accuracy_ci95", "balanced_accuracy", "precision", "precision_ci95", "recall", "recall_ci95",
            "f1", "auc", "brier", "brier_skill", "fpr", "fnr", "tp", "fp", "tn", "fn", "confidence_weighted_accuracy"]
    md += [_t([{"lead": L, **{c: s["models"][PROPOSED].get(c) for c in cols}, "reliable": s["reliability"]["reliable"]} for L, s in S.items()],
              ["lead", *cols, "reliable"]), ""]
    md += ["### Reliability checks", "", _t([{"lead": L, **s["reliability"]["checks"]} for L, s in S.items()],
                                             ["lead", "accuracy", "recall", "precision", "auc", "brier_skill", "era_accuracy"]), ""]
    md += ["### By era", "", _t([{"lead": L, "era": e, **{c: v.get(c) for c in ["n", "n_high", "accuracy", "recall", "precision", "auc", "brier"]}}
                                for L, s in S.items() for e, v in s["models"][PROPOSED]["eras"].items()],
                               ["lead", "era", "n", "n_high", "accuracy", "recall", "precision", "auc", "brier"]), ""]
    md += ["### Calibration (lead 1)", "", _t(S["1"]["models"][PROPOSED]["calibration"], ["bin", "n", "mean_p", "observed"]), ""]
    md += ["### Hunger level forecast (MAE, pp)", "", _t([{"lead": L, **s["level"]} for L, s in S.items()],
                                                        ["lead", "n", "mae_lgbm", "mae_persistence", "mae_skill_vs_persistence", "mae_diff_ci95", "mean_sigma"]), ""]
    md += ["## Consolidated comparison (same origins, targets and rules)", ""]
    rows = []
    for L, s in S.items():
        for name in [PROPOSED, *BASELINES, "Climatology (base rate)", "LightGBM classifier, direct (reference)"]:
            m, c = s["models"][name], s["vs_proposed"].get(name, {})
            rows.append({"lead": L, "model": name, **{k: m.get(k) for k in ["accuracy", "balanced_accuracy", "precision", "recall", "f1", "auc", "brier"]},
                         "brier_diff": c.get("brier_diff_proposed_minus_other"), "ci95": c.get("ci95"), "mcnemar_p": c.get("mcnemar_p")})
    md += [_t(rows, ["lead", "model", "accuracy", "balanced_accuracy", "precision", "recall", "f1", "auc", "brier", "brier_diff", "ci95", "mcnemar_p"]),
           "", "brier_diff = Brier(proposed) − Brier(other): negative favours the proposed LightGBM; 95 % moving-block bootstrap.", ""]
    md += ["## Does news help? Does each domain help? (Brier of the variant minus Brier of the full model; positive = the removed part helped)", ""]
    abl = [k for k in SPECS if k.startswith("LightGBM without")]
    md += [_t([{"lead": L, "full": s["models"][PROPOSED]["brier"], **{k.replace("LightGBM without ", "− "): s["models"][k]["brier"] - s["models"][PROPOSED]["brier"] for k in abl}}
               for L, s in S.items()], ["lead", "full", *[k.replace("LightGBM without ", "− ") for k in abl]]), ""]
    a = ev["audit"]
    md += ["## Overfitting and leakage audit", "",
           _t([{"lead": L, **v} for L, v in a["train_vs_oos"].items()], ["lead", "mean_train_accuracy", "oos_accuracy"]), "",
           _t([{"lead": L, **v} for L, v in a["label_permutation"].items()], ["lead", "n_perm", "auc_mean", "auc_sd", "real_auc", "share_perm_auc_ge_real"]), "",
           "Configurations chosen: " + json.dumps({L: s["configs"] for L, s in S.items()}), ""]
    md += ["## Live forecasts (issue " + fc["issue_quarter"] + f", seal `{fc['seal_sha256'][:16]}`)", "",
           _t(fc["forecasts"], ["lead", "target_quarter", "p_high", "class", "forecast_hunger_pct", "forecast_sigma_pp", "threshold_pct",
                                "latest_hunger_pct", "persistence_p_high", "logistic_p_high", "reliable_lead", "explanation"]), ""]
    imp = pd.read_csv(OUT / "shap_importance_by_domain.csv")
    md += ["## SHAP (mean |contribution| to the hunger-change forecast, pp, training rows)", "", _t(imp.to_dict("records"), list(imp.columns)), ""]
    lg, pv, se = (pd.read_csv(OUT / f) for f in ["lgu_rankings.csv", "province_priority.csv", "lgu_weight_sensitivity.csv"])
    md += ["## LGU priority (top 10 of 142)", "", _t(lg.head(10).to_dict("records"), ["rank", "lgu_name", "province_name", "poverty_incidence_2021",
                                                                                     "density_2024", "vulnerability", "priority_score", "forecast_status"]), "",
           _t(pv.to_dict("records"), ["province_name", "n_lgus", "vulnerability_popweighted", "priority_score", "lgus_in_top_third"]), "",
           _t(se.to_dict("records"), ["weights", "spearman_vs_equal", "top_third_changed"]), ""]
    vr = VALIDATION / "validation_result.json"
    md += ["## NLP human validation", "", "```json", vr.read_text() if vr.exists() else "{}", "```", "",
           "## Verification", "", "```json", json.dumps(ver, indent=1), "```"]
    DOCS.mkdir(parents=True, exist_ok=True)
    text = "\n".join(md)
    (DOCS / "RESULTS.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    build()
    print("written", DOCS / "RESULTS.md")
