from __future__ import annotations

import json

import numpy as np
import pandas as pd

from app.fi6.target import labels, quarterly
from app.fi9 import DOCS, MODEL, OUT
from app.fi9.evaluate import ABLATION, CLIM, DAMPED, DOMAIN_GOV, LGBM, PERSIST
