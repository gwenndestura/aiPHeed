"""Build docs/fi9/DATA_SOURCE_AND_VALIDATION_LOG.xlsx from the saved CSV outputs (needs openpyxl).

    python -m app.fi9.validation_log        # run with a venv that has openpyxl (e.g. aipheed_fi5_xpu)
"""
from __future__ import annotations

import pandas as pd

from app.fi9 import DOCS, OUT
from app.paths import BACKEND_DIR

D = BACKEND_DIR / "data"
FLAGS = [
    ("SWS hunger", "Balance Luzon, not CALABARZON", "CALABARZON is ~34% of the area's population; the forecast is regional context only", "documented; never assigned to provinces"),
    ("SWS hunger", "alternating survey jumps (sawtooth)", "lag-1 autocorrelation of changes -0.56 vs -0.28 expected from sampling error (FI8)", "sensitivity check; Lead 1 provisional"),
    ("PSA LFS unemployment", "national series used for a regional question", "regional LFS quarterly series with release dates not assembled", "flagged national proxy"),
    ("BSP remittances", "national, annual (World Bank WDI vintage)", "current vintage; revisions not reconstructed", "flagged national proxy; ablation: no contribution"),
    ("PSA poverty incidence", "methodology break 2015 -> 2018", "2006-2015 on the 2009 methodology (computed from provinces); 2018+ on the 2018 methodology", "documented; ablation: no contribution"),
    ("PSA CPI", "current vintage", "YoY from the downloaded series; first-release values not reconstructed", "documented"),
    ("Owner workbook ENNS provincial values", "secondary source (DEPDev RDP results matrix)", "primary FNRI tables blocked from this network; one survey year per province (2018, 2019 or 2021)", "unverified_secondary; excluded from training"),
    ("Owner workbook ENNS severe values", "scale inconsistency", "2021 severe 1.5-2.4% vs 2018-2019 severe 7.9-13.7%, consistent with different instruments or definitions across rounds", "not comparable; excluded"),
    ("FNRI 2015 HFIAS vs 2023 FIES", "different instruments", "HFIAS (30-day, 9 items) vs FIES (12-month, 8 items, Rasch)", "never pooled"),
    ("PIA 2025 regional figure", "news report", "secondary; no primary table", "provisional_secondary; not used"),
]


def vintage_summary() -> pd.DataFrame:
    v = pd.read_csv(OUT / "data_vintage_long.csv")
    g = v.groupby(["source_key", "indicator"])
    return g.agg(domain=("domain", "first"), geographic_level=("geographic_level", "first"), unit=("unit", "first"),
                 source=("source", "first"), first_period=("period_end", "min"), last_period=("period_end", "max"),
                 n_values=("value", "size"), last_available=("available_from", "max"),
                 revision_status=("revision_status", "first"), quality_status=("quality_status", "first")).reset_index()


def build() -> str:
    sheets = {
        "README": pd.DataFrame({"item": [
            "Purpose", "Labels", "Predictors", "Workbook", "Statuses", "Rule"], "text": [
            "Source and validation log for aiPHeed FI9 (Lead-1 food-insecurity outlook), generated by python -m app.fi9.validation_log",
            "SWS_targets: the only quarterly food-insecurity outcome (Balance Luzon); HFIAS_2015 / FIES_PSA: published benchmarks",
            "Predictor_series: every predictor series with its geographic level, availability rule and revision status",
            "Workbook_records / Workbook_benchmarks: the owner-supplied workbook, each record checked against primary sources",
            "verified_primary = equals the primary source downloaded by aiPHeed; unverified_secondary = secondary government document; provisional_secondary = news",
            "Only SWS_targets rows are training labels. No workbook record is a quarterly label."]}),
        "Sources_labels": pd.read_csv(D / "fi_labels" / "raw" / "MANIFEST.csv"),
        "Sources_predictors": pd.read_csv(D / "fi5" / "raw" / "MANIFEST.csv"),
        "SWS_targets": pd.read_csv(OUT / "sws_targets.csv"),
        "Predictor_series": vintage_summary(),
        "Workbook_records": pd.read_csv(D / "fi_labels" / "clean" / "owner_workbook_records_verified.csv"),
        "Workbook_benchmarks": pd.read_csv(D / "fi_labels" / "clean" / "owner_workbook_regional_benchmarks_verified.csv"),
        "HFIAS_2015": pd.read_csv(D / "fi_labels" / "clean" / "published_hfias_2015_calabarzon.csv"),
        "FIES_PSA": pd.read_csv(D / "fi_labels" / "clean" / "published_fies_psa_sdg212.csv"),
        "Discrepancies_flags": pd.DataFrame(FLAGS, columns=["series", "issue", "evidence", "handling"]),
        "Missing_data": pd.read_csv(OUT / "missing_data.csv"),
    }
    p = DOCS / "DATA_SOURCE_AND_VALIDATION_LOG.xlsx"
    with pd.ExcelWriter(p, engine="openpyxl") as w:
        for name, df in sheets.items():
            df.to_excel(w, sheet_name=name, index=False)
            ws = w.sheets[name]
            for col in ws.columns:
                ws.column_dimensions[col[0].column_letter].width = min(60, max(10, max(len(str(c.value or "")) for c in col[:50]) + 2))
            ws.freeze_panes = "A2"
    return str(p)


if __name__ == "__main__":
    print(build())
