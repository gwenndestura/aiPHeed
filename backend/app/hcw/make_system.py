def data_status(code: str | None, quarter: str) -> tuple[str, str]:
    """Completeness of this model's own main inputs (it has no remittance or fisheries input)."""
    rs = _rs(code, quarter)
    if not rs:
        return "unavailable", "The input values of this forecast were not recorded."
    labels = {"cpi_food_yoy": "food prices", "unemp_rate": "unemployment", "p_poverty": "poverty", "c_tc_4q": "typhoons",
              "l_rice_yoy": "local rice prices", "ag_palay_yoy": "rice harvest", "hh_grdp_g": "regional GRDP (2025)"}
    missing = [lab for c, lab in labels.items() if any(_val(r, c) is None for r in rs)]
    if not missing:
        return "complete", "All the main figures had been published when this forecast was made."
    return "incomplete", ("Not yet in the data when this forecast was made: " + ", ".join(missing) + ". Missing figures are "
                          "left out, never counted as low risk.")


