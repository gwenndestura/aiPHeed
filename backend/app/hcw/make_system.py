def build():
    s = SRC.read_text(encoding="utf-8")
    s = HEADER + s[s.index('from __future__'):]
    reps = [('DATA = Path(__file__).resolve().parents[3] / "data" / "e168" / "out"', 'DATA = Path(__file__).resolve().parents[3] / "data" / "hcw" / "out"'),
            ('MODEL_ID = "e168-lgbm-1.0"', 'MODEL_ID = "hcw-lgbm-1.0"'), ('m = t.get("E168", {})', 'm = t.get("HCW", {})'),
            ('"mode": f"E168_LEAD', '"mode": f"HCW_LEAD'), ('"e168_high_probability"', '"hcw_high_probability"'),
            ('return f"+e168:{p}', 'return f"+hcw:{p}'),
            ('"why_not_longer": "Lead 4 accuracy is below 75% (the model still beats the latest survey up to Lead 6)."',
             '"why_not_longer": "Lead 7 mean fold accuracy is 74.0%, below 75% (the model still beats the latest survey up to Lead 18)."'),
            ('"why_not_longer": "Lead 4 accuracy 73.6% is below 75% (it still beats the latest survey up to Lead 6)."',
             '"why_not_longer": "Lead 7 accuracy 74.0% is below 75% (it still beats the latest survey up to Lead 18)."'),
            ('"seal_issue_date": "ENNS 2022 forecasts"', '"seal_issue_date": None'),
            ('"protocol_name": "owner-defined acceptance (2026-11-07)"', '"protocol_name": "owner-defined acceptance (2026-11-07), applied to Setup H + class weights"')]
    for a, b in reps:
        assert a in s, a
        s = s.replace(a, b)
    # remaining user-facing mentions of the model name (imports use lowercase app.e168 and are untouched)
