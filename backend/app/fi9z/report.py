def j(p):
    return json.loads(p.read_text(encoding="utf-8"))


def f(x, d=2):
    return "–" if x is None or x != x else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def table(rows, cols):
    return "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n" + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)


def crow(name, v):
    m = v["full"]
    return [name, v["n"], f"{m['n_high']}/{m['n_low']}", m["predicted_high"], f(m["high_precision"]), f(m["high_recall"]), f(m["high_f1"]),
            f(m["low_precision"]), f(m["low_recall"]), f(m["low_f1"]), f(m["macro_f1"]), f(m["balanced_accuracy"]), f(m["accuracy"]),
            f"{m['tp']}/{m['fp']}/{m['fn']}/{m['tn']}", f(m["false_high_rate"]), f(m["missed_high_rate"]), f(m.get("roc_auc")), f(m.get("pr_auc")),
            f(m.get("brier"), 3), f(m.get("ece_5bin"), 3)]


CCOLS = ["Model", "n", "HIGH/LOW", "Pred. HIGH", "HIGH prec", "HIGH rec", "HIGH F1", "LOW prec", "LOW rec", "LOW F1", "Macro-F1", "Bal. acc",
         "Acc", "TP/FP/FN/TN", "False-HIGH rate", "Missed-HIGH rate", "ROC-AUC", "PR-AUC", "Brier", "ECE"]


