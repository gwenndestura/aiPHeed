"""Write docs/fi5/RESULTS.md from the pipeline outputs (numbers are read from data/fi5, never typed by hand).

    python -m app.fi5.report
"""
from __future__ import annotations

import json

import pandas as pd

from app.fi5.evaluate import BASELINES, PROPOSED, SPECS
from app.fi5.nlp import NLP
from app.fi5.paths import BACKEND_DIR, OUT

DOCS = BACKEND_DIR.parent / "docs" / "fi5"


def _f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and pd.isna(x)) else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def _table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(_f(r.get(c)) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def build() -> str:
    ev = json.loads((OUT / "evaluation.json").read_text())
    fc = json.loads((OUT / "forecast.json").read_text())
    ver = json.loads((OUT / "verification.json").read_text())
    lock = json.loads((OUT / "METHOD_LOCK.json").read_text())
    nlp = json.loads((NLP / "nlp_summary.json").read_text())
    S = ev["summary"]
    md = ["# FI5 results (generated by `python -m app.fi5.report`)", "",
          f"Lock `{lock['lock_sha256'][:16]}`; code matches lock: **{ev.get('lock', {}).get('code_matches_lock')}**. "
          f"Furthest reliable lead: **{ev['max_reliable_lead']}**.", ""]
    # G. LightGBM per lead
    md += ["## LightGBM (proposed), walk-forward, all evaluated targets 2010-Q1 onward", ""]
    rows = []
    for L, s in S.items():
        m = s["models"][PROPOSED]
        rows.append({"lead": L, **{k: m.get(k) for k in ["n", "n_high", "n_low", "accuracy", "precision", "recall", "f1",
                                                          "auc", "brier", "brier_skill", "fpr", "tp", "fp", "tn", "fn"]},
                     "reliable": s["reliability"]["reliable"]})
    md += [_table(rows, ["lead", "n", "n_high", "n_low", "accuracy", "precision", "recall", "f1", "auc", "brier",
                         "brier_skill", "fpr", "tp", "fp", "tn", "fn", "reliable"]), ""]
    md += ["### By era (accuracy / recall / AUC / n)", ""]
    rows = []
    for L, s in S.items():
        for era, e in s["models"][PROPOSED]["eras"].items():
            rows.append({"lead": L, "era": era, "n": e.get("n"), "n_high": e.get("n_high"), "accuracy": e.get("accuracy"),
                         "recall": e.get("recall"), "precision": e.get("precision"), "auc": e.get("auc"), "brier": e.get("brier")})
    md += [_table(rows, ["lead", "era", "n", "n_high", "accuracy", "precision", "recall", "auc", "brier"]), ""]
    md += ["### Reliability checks", ""]
    rows = [{"lead": L, **{k: v for k, v in s["reliability"]["checks"].items()}, "reliable": s["reliability"]["reliable"]} for L, s in S.items()]
    md += [_table(rows, ["lead", "accuracy", "recall", "precision", "auc", "brier_skill", "era_accuracy", "reliable"]), ""]
    # K. baselines
    md += ["## Consolidated comparison (identical origins and targets)", ""]
    rows = []
    for L, s in S.items():
        for name in [PROPOSED, *BASELINES, "Climatology (base rate)"]:
            m = s["models"][name]
            c = s["vs_proposed"].get(name, {})
            rows.append({"lead": L, "model": name, **{k: m.get(k) for k in ["n", "accuracy", "precision", "recall", "f1", "auc", "brier"]},
                         "brier_diff_vs_LGBM": c.get("brier_diff_proposed_minus_other"),
                         "ci95": "" if not c else f"[{c['ci95'][0]:.3f}, {c['ci95'][1]:.3f}]", "mcnemar_p": c.get("mcnemar_p")})
    md += [_table(rows, ["lead", "model", "n", "accuracy", "precision", "recall", "f1", "auc", "brier", "brier_diff_vs_LGBM", "ci95", "mcnemar_p"]),
           "", "brier_diff_vs_LGBM = Brier(LightGBM) − Brier(other); negative favours LightGBM; 95 % moving-block bootstrap interval.", ""]
    # contribution
    md += ["## Domain and news contribution (walk-forward ablations, Brier; lower is better)", ""]
    rows = []
    for L, s in S.items():
        base = s["models"][PROPOSED]["brier"]
        r = {"lead": L, "full": base}
        for name in SPECS:
            if name.startswith("LightGBM without"):
                r[name.replace("LightGBM without ", "minus ")] = s["models"][name]["brier"] - base
        rows.append(r)
    cols = ["lead", "full"] + [k.replace("LightGBM without ", "minus ") for k in SPECS if k.startswith("LightGBM without")]
    md += [_table(rows, cols), "", "Positive = removing that block made the forecast worse (the block helped).", ""]
    md += ["## Hunger level check (MAE, percentage points)", ""]
    md += [_table([{"lead": L, **s["level"]} for L, s in S.items()], ["lead", "n", "mae_lgbm", "mae_persistence", "mae_skill_vs_persistence"]), ""]
    # audit
    a = ev["audit"]
    md += ["## Overfitting audit", "",
           _table([{"lead": L, **v, "config_choices": json.dumps(v["config_choices"])} for L, v in a["train_vs_oos"].items()],
                  ["lead", "mean_train_accuracy", "oos_accuracy", "config_choices"]), "",
           _table([{k: p[k] for k in ["lead", "n_perm", "auc_mean", "auc_sd"]} for p in a["label_permutation"]],
                  ["lead", "n_perm", "auc_mean", "auc_sd"]), ""]
    # forecasts
    md += ["## Live forecasts", "", f"Issue quarter {fc['issue_quarter']}; seal sha256 `{fc['seal_sha256'][:16]}`.", ""]
    md += [_table([{k: f[k] for k in ["lead", "target_quarter", "p_high", "class", "persistence_class", "logistic_p_high", "reliable_lead"]} |
                   {"explanation": f["explanation"]} for f in fc["forecasts"]],
                  ["lead", "target_quarter", "p_high", "class", "persistence_class", "logistic_p_high", "reliable_lead", "explanation"]), ""]
    # rankings
    lg = pd.read_csv(OUT / "lgu_rankings.csv", dtype={"lgu_psgc": str})
    pv = pd.read_csv(OUT / "province_priority.csv")
    sens = pd.read_csv(OUT / "lgu_weight_sensitivity.csv")
    md += ["## Municipal and city priority (top 15 of 142)", "",
           _table(lg.head(15).to_dict("records"), ["rank", "lgu_name", "province_name", "lgu_type", "poverty_incidence_2021",
                                                   "density_2024", "vulnerability", "priority_score"]), "",
           _table(pv.to_dict("records"), ["province_name", "n_lgus", "poverty_popweighted", "density_2024",
                                          "vulnerability_popweighted", "priority_score", "lgus_in_top_third"]), "",
           _table(sens.to_dict("records"), ["weights", "spearman_vs_equal", "top_third_changed"]), ""]
    md += ["## NLP", "", "```json", json.dumps(nlp, indent=1), "```", ""]
    tp = pd.read_csv(NLP / "bertopic_topics.csv")
    md += [_table(tp[tp["topic"] >= 0].head(25).to_dict("records"), ["topic", "label", "domain", "n_all", "mean_stress", "representative_1"]), ""]
    md += ["## Independent verification", "", "```json", json.dumps(ver, indent=1), "```", ""]
    imp = pd.read_csv(OUT / "shap_importance_by_block.csv")
    md += ["## SHAP importance by block (sum of mean |SHAP|, training rows)", "", _table(imp.to_dict("records"), list(imp.columns)), ""]
    text = "\n".join(md)
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "RESULTS.md").write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    print(build()[:3000])
