"""Write docs/fi9n/NEWS_VALUE_REASSESSMENT.md from data/fi9n/out/news_study.json (no hand-typed numbers).

    python -m app.fi9n.report
"""
from __future__ import annotations

import json

from app.fi9n import DOCS, OUT
from app.fi9n.study import PROTOCOL

NAMES = {"QE1": "Next quarter, issued on the last day of the quarter (FI6-N 'Lead 1')",
         "OP1": "Next quarter, issued at the end of the quarter's 2nd month (FI9 Lead 1, served)",
         "OP1w": "Next quarter, FI9 issue date, news from the 90 days before issue",
         "QE2": "Two quarters ahead, quarter-end issue (FI6-N 'Lead 2')",
         "OP0": "Current quarter (nowcast), FI9 issue date"}
SHOW = ["Government only", "Government + news", "News + latest reading", "Naive persistence", "Damped persistence", "Climatology"]


def f(x, d=3):
    return "–" if x is None else f"{x:.{d}f}"


def table(rows, cols):
    return "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n" + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)


def ci(d, k="ci95"):
    return f"{d['mean']:+.4f} [{d[k][0]:+.4f}, {d[k][1]:+.4f}]"


def yn(b):
    return "**yes**" if b else "no"


def build() -> str:
    R = json.loads((OUT / "news_study.json").read_text())
    H = R["horizons"]
    rep = R["fi6n_reproduction"]["lead1"]
    t = (f"_Generated by `python -m app.fi9n.report` from data/fi9n/out (protocol `{R['protocol_sha256'][:12]}`). Do not edit by hand._\n\n"
         "# Does news improve aiPHeed's forecasts? Reassessment by horizon (FI9-N)\n\n"
         "## Correction to an earlier statement\n\n"
         "FI6-N's 'Lead 1' was described in this session as a current-quarter nowcast. That was imprecise. FI6-N issues "
         "on the **last day of quarter t** and targets **quarter t+1**. By the project's own definition (target = the "
         "calendar quarter after the issue quarter), that is a **next-quarter** forecast. It differs from the served FI9 "
         "Lead 1 in two ways:\n"
         "* it is issued one month later (end of quarter vs end of the quarter's 2nd month);\n"
         "* its news covers the complete issue quarter, instead of the last complete quarter before issue.\n\n"
         "Both read the same SWS quarter (the latest reading is about two quarters old in both). This study compares "
         "the horizons on identical issue dates.\n\n## 1. Reproduction of FI6-N\n\n")
    t += table([[c, f(rep["recomputed"][c]["accuracy"]), f(rep["recomputed"][c]["recall"]), f(rep["recomputed"][c]["auc"]),
                 f(rep["recomputed"][c]["brier"]), f(rep["reported_brier"][c])] for c in rep["recomputed"]],
               ["Model (FI6-N Lead 1)", "Accuracy", "Recall", "AUC", "Brier (recomputed)", "Brier (reported)"])
    d, r_ = rep["recomputed_gov_news_minus_gov"], rep["reported_gov_news_minus_gov"]
    t += (f"\n* Government + news minus government only, Brier: recomputed {d[0]:+.4f} [{d[1]:+.4f}, {d[2]:+.4f}]; "
          f"reported {r_[0]:+.4f} [{r_[1]:+.4f}, {r_[2]:+.4f}].\n"
          f"* Re-running FI6-N's models from its code and data gives the same predictions: max |Δp| "
          f"{max(R['rerun_vs_fi6n_saved_max_abs_p_diff']['QE1'].values()):.1e} (Lead 1), "
          f"{max(R['rerun_vs_fi6n_saved_max_abs_p_diff']['QE2'].values()):.1e} (Lead 2).\n"
          "* This is a computational reproduction on the same data, not new evidence. The QE1 result was known "
          "before this study's lock. The robustness checks below (eras, sawtooth, 5-horizon Bonferroni) are new.\n\n"
          "## 2. Results by horizon (62 target quarters, 11 HIGH; FI6-N LightGBM change model, class at p ≥ 0.5)\n\n")
    for h in ["QE1", "OP1", "OP1w", "QE2", "OP0"]:
        X = H[h]
        t += f"### {h}: {NAMES[h]}\n\nIssue dates e.g. {', '.join(X['issue_dates_example'])}; mean age of the latest SWS reading {X['mean_age_of_latest_reading_q']:.1f} quarters.\n\n"
        t += table([[c, f(X["metrics"][c]["accuracy"]), f(X["metrics"][c]["recall"]), f(X["metrics"][c]["balanced_accuracy"]),
                     f(X["metrics"][c]["auc"]), f(X["metrics"][c]["brier"]), f(X["metrics"][c]["ece_5bin"]),
                     "pass" if X["metrics"][c]["reliability_fi7"]["passes"] else "fail"] for c in SHOW],
                   ["Model", "Accuracy", "Recall", "Bal. acc", "AUC", "Brier", "ECE", "FI7 rule"])
        n, nl = X["news_vs_no_news"], X["news_latest_vs_no_news"]
        t += table([
            ["Government + news vs government only (Brier, 95 % CI)", ci(n)],
            ["… 99 % Bonferroni CI (5 horizons)", ci(n, "ci99_bonferroni5")],
            ["… AUC change", f"{n['auc_diff']:+.3f}"],
            ["… recall change / McNemar p (accuracy)", f"{n['recall_diff']['mean']:+.3f} / {n['mcnemar_p']:.2f}"],
            ["News + latest reading vs government only (Brier)", ci(nl)],
            ["… recall change / McNemar p", f"{nl['recall_diff']['mean']:+.3f} (CI {nl['recall_diff']['ci95'][0]:.2f}–{nl['recall_diff']['ci95'][1]:.2f}) / {nl['mcnemar_p']:.2f}"],
            ["Government + news vs naive persistence (Brier)", ci(X["gov_news_vs_persistence"])],
            ["News + latest reading vs naive persistence (Brier)", ci(X["news_latest_vs_persistence"])],
            ["News gain by era (2016–20 / 2021–26, Brier)", " / ".join(f"{X['by_era_news_minus_no_news'][e]['mean_brier_diff']:+.4f}" for e in ["2016-2020", "2021-2026"])],
            ["News gain without sawtooth quarters", ci(X["without_sawtooth"]["news_vs_no_news"])],
            ["News gain on origins with news", ci(X["origins_with_news"]["news_vs_no_news"])],
            ["Brier rise when one news domain is removed (P worse)", "; ".join(f"{k} {v['mean']:+.4f} ({1 - v['p_better']:.2f})" for k, v in X["news_domain_removal"].items())],
        ], ["Test", "Result"])
        t += "\n"
    t += "## 3. Decisions (locked rules)\n\n"
    keys = list(H["QE1"]["decisions"])
    t += table([[h] + [yn(H[h]["decisions"][k]) for k in keys] for h in ["QE1", "OP1", "OP1w", "QE2", "OP0"]],
               ["Horizon"] + [k.replace("_", " ") for k in keys])
    q = H["QE1"]
    t += (
        "\n## 4. Conclusions\n\n"
        f"**Does news improve next-quarter forecasting?** Yes for probability quality when the forecast is issued on the "
        f"last day of the quarter (QE1). Adding news to the government model lowers Brier by {-q['news_vs_no_news']['mean']:.4f}. "
        "The interval stays below zero:\n"
        f"* at 95 % and under the 5-horizon Bonferroni correction ({ci(q['news_vs_no_news'], 'ci99_bonferroni5')});\n"
        f"* without the sawtooth quarters;\n"
        f"* in both eras with news coverage (most of the gain is in 2021–2026).\n\n"
        f"AUC rises by {q['news_vs_no_news']['auc_diff']:+.3f}, and calibration error falls from "
        f"{f(q['metrics']['Government only']['ece_5bin'])} to {f(q['metrics']['Government + news']['ece_5bin'])}. The "
        "information is spread across domains: removing any one domain costs 0.002–0.005 Brier, with poverty news "
        "largest.\n\n"
        f"At the FI9 issue date (OP1) the gain is not significant ({ci(H['OP1']['news_vs_no_news'])}), and fresher 90-day "
        f"news windows do not restore it ({ci(H['OP1w']['news_vs_no_news'])}). A possible explanation, not tested here, "
        "is that the useful news falls in the last month of the issue quarter.\n\n"
        f"**Does news improve current-quarter nowcasting?** No ({ci(H['OP0']['news_vs_no_news'])}).\n\n"
        "**Does news improve probability quality even when accuracy does not improve?** Yes, at QE1:\n"
        "* Government + news makes exactly the same HIGH/LOW calls as government only, with better probabilities.\n"
        "* News + latest reading catches one more HIGH quarter (accuracy 0.839 → 0.855). That one-quarter difference "
        f"is not significant (McNemar p = {q['news_latest_vs_no_news']['mcnemar_p']:.2f}).\n\n"
        "**Does news add value beyond the latest SWS observation?** No. At every horizon, the best news configuration "
        f"is not better than naive persistence. At QE1: {ci(q['gov_news_vs_persistence'])} for government + news, and "
        f"{ci(q['news_latest_vs_persistence'])} for news + latest reading. Persistence passes the FI7 reliability rule; "
        "no news model does.\n\n"
        "**Is the improvement statistically and operationally meaningful?** It is statistically meaningful, narrowly, "
        "for LightGBM probability quality at QE1. It is not operationally meaningful under the locked rule: no news "
        "configuration both passes the reliability rule and beats persistence. The served FI9 forecaster therefore "
        "stays damped persistence. News remains a measured, documented contributor to model probability quality at "
        "the quarter-end issue, not to the served next-quarter forecast.\n\n"
        "**Sawtooth side-finding.** At the current-quarter nowcast (OP0) the latest reading is only one quarter old, "
        "and naive persistence is worse (Brier "
        f"{f(H['OP0']['metrics']['Naive persistence']['brier'])} vs {f(q['metrics']['Naive persistence']['brier'])} at QE1). "
        "Since 2010, a reading two quarters old has been closer to the outcome than a reading one quarter old (mean "
        "absolute difference 4.16 vs 4.76 points), which is the alternating survey pattern documented in "
        "docs/fi9r/SURVEY_SAWTOOTH_INVESTIGATION.md.\n\n"
        "## 5. What is preserved\n\n"
        "The XLM-R zero-shot classifier (OpenVINO on the Arc GPU), BERTopic topics, the FSSI index and the FI6-N "
        "publisher archive (62,698 articles; restated statistics removed) are unchanged in `app/fi5`, `app/fi6` and "
        "`data/fi6/news_archive`. The FI6-N predictions and report are unchanged. News stays in the LightGBM research "
        "models and as dashboard context.\n\n"
        "## 6. Thesis wording supported by this evidence\n\n"
        "> Properly collected news improved the probability quality (Brier, AUC and calibration) of the LightGBM "
        "next-quarter model when forecasts were issued at the end of the quarter, and the improvement survived "
        "correction for multiple horizons and the survey-alternation check. News did not change the model's HIGH/LOW "
        "classifications, did not improve the forecast issued one month earlier, did not improve the current-quarter "
        "nowcast, and did not outperform the latest SWS reading.\n")
    (DOCS / "NEWS_VALUE_REASSESSMENT.md").write_text(t, encoding="utf-8")
    return str(DOCS / "NEWS_VALUE_REASSESSMENT.md")


if __name__ == "__main__":
    print(build())
