"""Write docs/fi9x/FI9X_POVERTY_WEIGHTING_VALIDATION_REPORT.md from data/fi9x/out/priority_validation.json.

    python -m app.fi9x.priority_report
"""
from __future__ import annotations

import json

import pandas as pd

from app.fi9x import DOCS, OUT

CUR, MOD, STR, POV, DEN = ("current (0.5 poverty / 0.5 density)", "moderate (0.65 / 0.35)", "strong (0.8 / 0.2)",
                           "poverty only (benchmark)", "density only (reference)")
ORDER = [CUR, MOD, STR, POV, DEN]


def table(rows, cols):
    return "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n" + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)


def build() -> str:
    J = json.loads((OUT / "priority_validation.json").read_text())
    P, L = J["provincial"], J["lgu"]
    lg = pd.read_csv(OUT / "priority_alternatives_lgu.csv", dtype={"lgu_psgc": str})
    t = "# FI9-X poverty-weighting validation (provincial and LGU priority)\n\n"
    t += ("_Generated by `python -m app.fi9x.priority_report` from `backend/data/fi9x/out/priority_validation.json`, "
          "`priority_alternatives_province.csv` and `priority_alternatives_lgu.csv`. Production is unchanged._\n\n"
          "## 1. Current formula and indicator weights\n\n"
          "`app/fi5/rankings.py` (served by FI9):\n"
          "* **LGU vulnerability:** V = 0.5 × percentile rank of poverty incidence (PSA 2021 city/municipal small-area "
          "estimates; Lucena City uses PSA's published 2021 HUC estimate) + 0.5 × percentile rank of population density "
          "(POPCEN 2024 population ÷ land area). Ranks are within the 142 CALABARZON LGUs.\n"
          "* **LGU priority** = 100 × P(HIGH, regional outlook) × V. P is the same for every LGU, so the order is set by V alone.\n"
          "* **Province priority** = population-weighted mean of its LGUs' V (× the same P).\n"
          "* The equal weights were a stated normative default (OECD/JRC composite-indicator guidance). They were never "
          "estimated from an outcome.\n\n"
          "## 2. Weighting scenarios (fixed before looking at the validation)\n\n")
    t += table([[k, v, round(1 - v, 2)] for k, v in J["formula"]["scenarios"].items()], ["Scenario", "Poverty weight", "Density weight"])
    t += "\nA 0–1 sweep in steps of 0.05 is reported as a curve. Weights are **not** chosen by maximum correlation.\n\n## 3. Province-by-province comparison\n\n"
    pt = pd.DataFrame(P["province_table"])
    t += table([[r["province"], r["hfias2015_mod_sev"], r["hfias_rank"], round(r["poverty2021_popweighted"], 1), round(r["density2024"]),
                 *[f"{r[f'score | {s}']:.3f} (#{r[f'rank | {s}']})" for s in ORDER]] for _, r in pt.iterrows()],
               ["Province", "HFIAS 2015 mod+sev %", "HFIAS rank", "Poverty 2021 % (pop-weighted)", "Density /km²", "Current", "Moderate", "Strong", "Poverty only", "Density only"])
    t += "\nProvince order as the poverty weight rises:\n\n"
    seen, rows = None, []
    for s in P["sweep"]:
        if s["order"] != seen:
            rows.append([f"from {s['w_poverty']:.2f}", s["order"], f"{s['spearman_mod_sev']:+.2f}"])
            seen = s["order"]
    t += table(rows, ["Poverty weight", "Order (highest priority first)", "Spearman vs HFIAS 2015"])
    t += "\n## 4. FNRI 2015 validation\n\n"
    rows = []
    for s in ORDER:
        m = P["scenarios"][s]["mod_sev"]
        rows.append([s, f"{m['spearman']:+.2f}", f"{m['kendall']:+.2f}", f"{m['exact_p_one_sided']:.3f}", f"{m['mean_spearman_under_hfias_sampling']:+.2f}",
                     "–" if m["prob_better_than_current_under_sampling"] is None else f"{m['prob_better_than_current_under_sampling']:.2f}",
                     ", ".join(f"{x:+.1f}" for x in m["leave_one_province_out_spearman"]), f"{m['lopo_better_than_current']}/5",
                     f"{P['scenarios'][s]['severe']['spearman']:+.2f}", f"{P['scenarios'][s]['not_food_secure']['spearman']:+.2f}"])
    t += table(rows, ["Scenario", "Spearman (mod+sev)", "Kendall", "Exact p (one-sided)", "Mean Spearman under HFIAS sampling error",
                      "P(better than current) under sampling", "Leave-one-province-out Spearman", "LOPO better than current", "Spearman (severe)", "Spearman (not food secure)"])
    pw = P["hfias_pairwise_distinguishable"]
    t += ("\n* **Direction:** agreement rises with the poverty weight and reaches a plateau from 0.70 upward, so it does not hinge "
          "on one exact weight. Density alone ranks the provinces opposite to the survey "
          f"(ρ = {P['density_vs_hfias2015_spearman']:+.2f}).\n"
          f"* **Time mismatch:** the formula uses 2021 poverty; the survey is 2015. Poverty 2021 vs HFIAS 2015: ρ = "
          f"{P['poverty2021_vs_hfias2015_spearman']:+.2f}; poverty 2015 vs HFIAS 2015: ρ = 1.00 (FI9-X label report).\n"
          f"* **Strength of the reference:** none of the {pw['n_pairs']} province pairs differs significantly in the 2015 survey "
          f"(largest z = {max(pw['z_scores'].values()):.2f}, Laguna–Quezon). The survey separates Quezon from the rest only "
          "weakly, and the other four are statistically tied. Even the best scenario reaches an exact p = "
          f"{P['scenarios'][STR]['mod_sev']['exact_p_one_sided']:.3f} with n = 5.\n"
          "* **The evidence is one survey wave (2015), five provinces, HFIAS instrument.** It indicates a direction. It "
          "cannot calibrate weights.\n\n## 5. LGU data suitability\n\n")
    d = L["data"]
    t += table([["Poverty", f"PSA {d['poverty_year']} city/municipal small-area estimates (141) + Lucena HUC estimate (1)",
                 f"CV ≤10 %: {d['cv_bins']['<=10%']}, 10–20 %: {d['cv_bins']['10-20%']}, 20–30 %: {d['cv_bins']['20-30%']}, >30 %: {d['cv_bins']['>30%']}, no CV: {d['cv_bins']['no CV (Lucena)']}",
                 "Model-based SAE with 90 % CIs. 25 LGUs exceed the 20 % CV caution line. Lucena's value is a whole-percent HUC estimate with no CV."],
                ["Density", f"POPCEN {d['density_year']} population ÷ land area", "census count; no sampling error", "Measures concentration, not food-insecurity risk by itself"],
                ["LGU food-insecurity outcome", "none", "–", "No municipal HFIAS/FIES exists; provincial labels are **not** copied to LGUs"]],
               ["Indicator", "Source and year", "Reliability", "Notes"])
    t += (f"\n* Across LGUs, poverty and density are negatively correlated (ρ = {d['spearman_poverty_vs_density']:+.2f}). Dense urban "
          "LGUs are less poor, so equal weights partly cancel, and density lifts urbanised, less poor LGUs.\n"
          f"* The number of poor people (poverty × population) correlates {L['scale_indicator_note']['spearman_poor_population_vs_density']:+.2f} "
          f"with density and only {L['scale_indicator_note']['spearman_poor_population_vs_poverty_rate']:+.2f} with the poverty rate. "
          "Density partly stands in for scale (how many people are affected), a dimension a rate-based index lacks.\n\n"
          "## 6. Sensitivity and stability (LGU level)\n\n")
    rows = []
    for s in ORDER:
        v = L["scenarios"][s]
        rows.append([s, f"{v['spearman_vs_current']:.2f}", v["top_third_changed_vs_current"], ", ".join(f"{k} {n}" for k, n in v["top_third_by_province"].items()),
                     f"{v['share_lgus_with_stable_top_third_membership']:.2f}", f"{v['median_90pct_rank_interval_width']:.0f}",
                     f"{v['median_rank_interval_width_lgus_cv_gt_20']:.0f}", v["drop_cv_gt_30_top_third_changed"]])
    t += table(rows, ["Scenario", "Spearman vs current", "Top-third LGUs changed (of 48)", "Top third by province", "Share of LGUs with stable top-third membership",
                      "Median 90 % rank interval", "… for LGUs with CV > 20 %", "Top-third change if CV > 30 % LGUs dropped"])
    unc = lg[(lg[f"p_top_third | {CUR}"].between(0.1, 0.9)) | (lg[f"p_top_third | {MOD}"].between(0.1, 0.9))]
    t += (f"\nUncertainty is simulated with 2,000 draws of every LGU's poverty from its SAE confidence interval. 'Stable' means "
          "an LGU is in, or out of, the top third in at least 90 % of draws. Under both the current and moderate formulas, "
          f"{len(unc)} LGUs have uncertain top-third membership. They are listed in "
          "`priority_alternatives_lgu.csv` (`p_top_third` columns).\n\n"
          "**Reading.** More poverty weight makes top-third membership somewhat more stable but rank positions less "
          "precise, because poverty carries sampling error and density does not. Dropping the four LGUs with CV > 30 % "
          "barely changes anything. Missing data are not an issue (one substituted value, Lucena).\n\n"
          "## 7. Limitations and unresolved evidence gaps\n\n"
          "* **One provincial survey wave (2015), five provinces, HFIAS:** too little to estimate weights. A direction only.\n"
          "* **Time gap:** 2015 survey vs 2021 poverty and 2024 density.\n"
          "* **No LGU-level food-insecurity outcome:** the LGU weighting cannot be validated at all. Provincial agreement "
          "does not transfer to municipalities.\n"
          "* **Imprecise LGU poverty:** 25 LGUs have SAE CVs above 20 %.\n"
          "* **Density's role is conceptual, not empirical:** exposure/scale. A scale indicator such as the number of poor "
          "people may represent that dimension better (not tested against an outcome).\n"
          "* **Evidence that would settle it:** provincial FIES from the 2023 NNS household file (~384 households per "
          "province); any municipal food-insecurity data (e.g. CBMS); a second FNRI wave.\n\n"
          "## 8. Recommendation\n\n"
          "**Partially adopt, at the provincial level only, after owner approval. Retain the current LGU formula.**\n\n"
          "1. **Provinces: use the moderate weighting (0.65 poverty / 0.35 density).**\n"
          "   * It is the smallest pre-defined change that improves agreement with the only measured provincial "
          "food-insecurity data (ρ +0.30 → +0.50).\n"
          f"   * It has the highest probability of being better under the survey's sampling error ({P['scenarios'][MOD]['mod_sev']['prob_better_than_current_under_sampling']:.2f}).\n"
          "   * Density keeps a real role.\n"
          "   * The strong and poverty-only versions agree more (+0.80), but choosing them would fit five statistically "
          "tied observations and let poverty dominate. They are reported as sensitivity bounds.\n"
          "2. **LGUs: keep the current equal weights in production.**\n"
          "   * Show the moderate-weighted rank alongside it for comparison.\n"
          "   * Flag the LGUs whose top-third membership is uncertain under either formula.\n"
          "   * No LGU outcome exists to justify changing local weights, and 9 of 48 top-third LGUs would change.\n"
          "3. The alternatives are served read-only at `GET /api/v1/fi9/priority/alternatives` for comparison. A "
          "provincial FIES estimate from the 2023 NNS would be the next validation.\n\n"
          "## 9. Decision and implementation (2026-11-03)\n\n"
          "**The owner approved step 1 (provinces only).**\n"
          "* `app/fi9/serve.py` now builds the served province priority (`/api/v1/fi9/priority`, `province_priority.csv`) "
          "from the LGUs' vulnerability recomputed with 0.65 poverty / 0.35 density.\n"
          "* The LGU ranking, its bands and the forecast model are unchanged. The LGU ranks were verified identical "
          "before and after.\n"
          "* Each served file carries a `weights` column, and the change is logged in "
          "`backend/data/fi9/PRODUCTION_PIN.json`.\n"
          "* The served province order (Quezon > Cavite > Rizal > Batangas > Laguna) equals the moderate scenario above.\n")
    (DOCS / "FI9X_POVERTY_WEIGHTING_VALIDATION_REPORT.md").write_text(t, encoding="utf-8")
    return str(DOCS / "FI9X_POVERTY_WEIGHTING_VALIDATION_REPORT.md")


if __name__ == "__main__":
    print(build())
