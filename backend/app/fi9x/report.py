def f(x, d=3):
    return "–" if x is None or x != x else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def table(rows, cols):
    return "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n" + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)


def d(v):
    return f"{v['mean']:+.4f} [{v['ci95'][0]:+.4f}, {v['ci95'][1]:+.4f}], P {v['p_negative']:.2f}" if v else "–"


def x_better(s) -> bool:
    v = s.get("vs_naive")
    return bool(v and v["mean"] < 0 and v["p_negative"] >= 0.90)


def recompute_check(W, E) -> float:
    worst = 0.0
    for o, G in W.groupby("origin"):
        for c, g in G.groupby("config"):
            mine, rep = _recompute(g), E[o]["full"]["models"][c]
            for k, v in mine.items():
                if v is not None and rep.get(k) is not None:
                    worst = max(worst, abs(v - rep[k]))
    return worst


