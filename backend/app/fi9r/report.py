        ["CBMS (community-based monitoring)", "Households in every LGU", "Not verified (food-insecurity items reported in some rounds)", "Irregular", "Not verified", "Held by LGUs/PSA; access is by request (not pursued)", "Most promising for LGU outcomes if released"],
