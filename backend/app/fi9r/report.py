C0, NV = "C0 damped persistence (FI9)", "Naive persistence"
ORDER = ["Always LOW", "Always HIGH", NV, C0, "C1 local level", "C1b damped local level", "C2 recalibrated damped",
         "FI9 LightGBM (saved)", "FI9 logistic (saved)"]
DOMS = ["C3 market", "C3 climate", "C3 employment", "C3 remittance", "C3 poverty", "C3 news"]
HEAD = "_Generated by `python -m app.fi9r.report` from data/fi9r/out (FI9-R protocol `{sha}`). Do not edit by hand._\n\n"


def f(x, d=3):
    return "–" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def table(rows, cols):
    return "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n" + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in rows)


def mrow(t, s):
    v0, vn = s.get("vs_C0"), s.get("vs_naive")
    return [t, f"{s['n']}/{s['n_high']}", f(s["accuracy"]), f(s["balanced_accuracy"]), f(s["precision"]), f(s["recall"]), f(s["f1"]),
            f(s["roc_auc"]), f(s["pr_auc"]), f(s["brier"]), f(s["log_loss"]), f(s["ece_5bin"]), s["confusion"]["fn"],
            f"{v0['mean']:+.4f} ({v0['p_negative']:.2f})" if v0 and t != C0 else "–",
            f"{vn['mean']:+.4f} ({vn['p_negative']:.2f})" if vn and t != NV else "–"]


MCOLS = ["Model", "n/HIGH", "Acc", "Bal acc", "Prec", "Recall", "F1", "ROC-AUC", "PR-AUC", "Brier", "Log loss", "ECE", "FN",
         "ΔBrier vs C0 (P better)", "ΔBrier vs naive (P better)"]


def build() -> list[str]:
    S = json.loads((OUT / "reassessment.json").read_text())
    A = json.loads((OUT / "adoption.json").read_text())
    T = json.loads((OUT / "sawtooth.json").read_text())
    AU = json.loads((OUT / "audit.json").read_text())
    AU9 = json.loads((FI9OUT / "audit.json").read_text())
    FC = json.loads((FI9OUT / "forecast.json").read_text())
    ART = json.loads((MODEL / "lead1_model.json").read_text())
    PIN = json.loads((BACKEND_DIR / "data" / "fi9" / "PRODUCTION_PIN.json").read_text())
    P = S["periods"]
    F, B, N, D = (P[k]["models"] for k in ("full", "B_previously_examined", "full_without_sawtooth", "A_development"))
    sha = S["protocol_sha256"]
    w = lambda name, text: (DOCS / name).write_text(HEAD.format(sha=sha[:12]) + text, encoding="utf-8")
    c0, nv, lo = F[C0], F[NV], F["Always LOW"]
    ci = S["metric_ci95_full"][C0]
    loo = pd.DataFrame(S["leave_one_high_out"][C0])
    reg = PR.read()
    out = []

    # ------------------------------------------------------------------ 2. sawtooth
    cs, de, md = T["change_structure"], T["design"], T["metadata"]
    wls, wla = de["wls_2023Q2_on_trend"], de["wls_adult_base_2025Q2_on_trend"]
    t = "# SWS survey-sawtooth investigation\n\n## 1. Metadata available in the SWS releases\n\n"
    t += table([[k.replace("_", " "), v] for k, v in md.items()], ["Item", "Value"])
    t += ("\nOnly 15 of 115 rounds state the Balance Luzon sample size (2021-Q3 and 2023-Q2 onward). The 92 pre-2021 rounds "
          "carry an **assumed** ±6-point margin of error and a **rule-based** release date (fieldwork month end + 60 days). "
          "No questionnaire change for the hunger item is stated in the releases we hold; the respondent base changed from "
          "household heads to adults with the April 2025 round. Questionnaire wording, round identifiers and weights are not "
          "in our files and were not invented.\n\n## 2. Structure of quarter-to-quarter changes\n\n")
    t += table([[e, v["n_changes"], f(v["lag1_autocorr_changes"], 2), f(v["expected_lag1_if_sampling_noise_only"], 2),
                 f(v["share_of_change_variance_from_sampling"], 2)] for e, v in cs.items()],
               ["Era", "Changes", "Lag-1 autocorrelation", "Expected from sampling noise alone", "Share of change variance from sampling"])
    t += ("\nIf the true level moved smoothly and the only extra noise were sampling error, changes would have a lag-1 "
          "autocorrelation near the 'expected' column. The observed values are about twice as negative in every era: "
          "readings bounce back more than sampling error explains.\n\n## 3. Survey design: rounds with 300 vs 600+ Balance Luzon respondents\n\n")
    t += table([[r["fieldwork"], int(r["bl_n"]), r["area_moe_bl"], r["balance_luzon"], r["respondent_base"]] for r in de["rounds"]],
               ["Fieldwork", "BL respondents", "MOE", "Hunger %", "Respondent base"])
    t += (f"\nWeighted regression on a linear trend (rounds 2023-Q2 onward, n = {wls['n_rounds']}): rounds with 300 respondents read "
          f"**{wls['effect_small_minus_large_pp']:.1f} points** lower than larger rounds (SE {wls['se']:.1f}, p = {wls['p_two_sided']:.3f}). "
          f"Adult-respondent rounds only (n = {wla['n_rounds']}): {wla['effect_small_minus_large_pp']:.1f} (SE {wla['se']:.1f}, "
          f"p = {wla['p_two_sided']:.3f}). Each 300-respondent round that sits between two larger rounds is lower than both "
          f"neighbours (mean {de['sandwiched_mean_diff_pp']:+.1f} points; "
          + "; ".join(f"{x['round']}: {x['value']} vs {x['neighbours_mean']:.1f}" for x in de["sandwiched_small_rounds"]) + ").\n\n")
    t += ("**Reading.** Sample size alone changes precision, not the expected level, so a systematic gap points to the two "
          "round types being different survey vehicles or designs (e.g. different sampling frames, timing or respondent "
          "selection). Real hunger cannot plausibly alternate up and down by 5–7 points every quarter in step with sample "
          "size. Since 2025 the alternation coincides with the switch to adult respondents, so respondent composition and "
          "design are confounded. Before 2021 the releases give no sample size, so the older sawtooth cannot be attributed.\n\n")
    da = S["design_adjusted_diagnostic"]
    t += "## 4. Treatments and their effect\n\n"
    rows = [["1. Original published readings (FI9)", f"C0 Brier {f(c0['brier'])}, recall {f(c0['recall'])}", "Defensible; the target is the published figure"],
            ["2. Design-aware adjustment (300 vs 600+)", f"Brier {da['brier_raw']:.3f} → {da['brier_adjusted']:.3f} on {da['n']} targets 2024+ (worse)",
             "Not adopted: sample sizes exist only from 2023; the effect is estimated, not documented by SWS; it does not help forecast the published figure"],
            ["3. Sampling-uncertainty-aware scoring", f"C0 soft-label Brier {f(c0['soft_label_brier'])} vs naive {f(nv['soft_label_brier'])}",
             "Defensible as a diagnostic; ranking unchanged"],
            ["4. Robust measurement model (local-level filter, C1)", f"Brier {f(F['C1 local level']['brier'])}, recall {f(F['C1 local level']['recall'])}",
             "Defensible but no gain (rejected by the adoption rule)"],
            ["5. Exclude sawtooth quarters (diagnostic)", f"C0 recall {f(N[C0]['recall'])}, reliability {'pass' if N[C0]['reliability']['passes'] else 'fail'}",
             "Diagnostic only; quarters are never removed from scoring"]]
    t += table(rows, ["Treatment", "Effect on historical forecasts", "Decision"])
    lv = S["live_2026_11_03"]
    t += (f"\nCurrent forecast ({lv['target_quarter']}): the latest reading {lv['latest']} % comes from a round with "
          f"{int(lv['latest_round_bl_n'][0])} respondents. C0 projects {lv['C0']['level']:.1f} % (p = {lv['C0']['p']:.2f}); the "
          f"local-level filter {lv['C1_local_level']['level']:.1f} % (p = {lv['C1_local_level']['p']:.2f}); naive persistence "
          f"{lv['naive']['level']} %. A design adjustment would lower the latest reading by about "
          f"{abs(wls['effect_small_minus_large_pp']) / 2:.1f} points to a common design.\n\n## 5. Conclusion\n\n"
          "The recent sawtooth is largely a survey-design effect (300- vs 600-respondent rounds), measured at about 5 points "
          "with p ≈ 0.04 on 14 rounds. It cannot be separated cleanly from genuine change or respondent composition, and the "
          "older sawtooth cannot be attributed at all. No adjustment is applied to the target. The effect is disclosed on the "
          "dashboard. Resolving it needs SWS documentation of the two round types (sampling design, timing, sponsorship) or "
          "the round microdata.\n")
    w("SURVEY_SAWTOOTH_INVESTIGATION.md", t)
    out.append("SURVEY_SAWTOOTH_INVESTIGATION.md")

    # ------------------------------------------------------------------ 4. baselines
    t = ("# FI9 baseline comparison (Lead 1, matched dates)\n\nEvery model is evaluated on the same issue dates with the "
         "same publication cutoffs. C0 = current production model. ΔBrier < 0 means better; P is the block-bootstrap "
         "probability that the model is better. FN = missed HIGH quarters.\n\n")
    for k, name in [("full", "All historical targets (A + B)"), ("A_development", "A. Development (2010–2017)"),
                    ("B_previously_examined", "B. Previously examined (2018–2026; not an untouched test)"),
                    ("full_without_sawtooth", "Diagnostic: without sawtooth quarters")]:
        t += f"## {name}\n\n" + table([mrow(m, P[k]["models"][m]) for m in ORDER if m in P[k]["models"]], MCOLS) + "\n"
    t += "## 95% block-bootstrap intervals of the main metrics (all historical targets)\n\n"
    t += table([[m] + [f"{v[0]:.2f}–{v[1]:.2f}" for v in S["metric_ci95_full"][m].values()] for m in S["metric_ci95_full"]],
               ["Model"] + list(next(iter(S["metric_ci95_full"].values())).keys()))
    t += ("\n## Decision\n\nNaive persistence has the lowest Brier and highest accuracy; C0 has higher recall at the cost "
          "of precision. Neither differs from the other with any confidence. No model beats naive persistence. The confidence "
          "intervals of every metric overlap widely. C0 is retained because it was selected by the locked FI9 rule; this "
          "report does not show it to be better than naive persistence.\n")
    w("FI9_BASELINE_COMPARISON_REPORT.md", t)
    out.append("FI9_BASELINE_COMPARISON_REPORT.md")

    # ------------------------------------------------------------------ 5. calibration & intervals
    t = "# FI9 calibration and interval report\n\n## Probability calibration (all historical targets)\n\n"
    t += table([[m, f(F[m]["brier"]), f(F[m]["log_loss"]), f(F[m]["ece_5bin"]), f(F[m]["calibration_line"]["intercept"], 2),
                 f(F[m]["calibration_line"]["slope"], 2)] for m in [C0, NV, "C1 local level", "C2 recalibrated damped", "Always LOW"]],
               ["Model", "Brier", "Log loss", "ECE", "Intercept", "Slope"])
