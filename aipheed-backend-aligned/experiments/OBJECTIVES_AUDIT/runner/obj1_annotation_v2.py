"""Objective 1 human validation, version 2: disagreement tracking, adjudication and the full metric set.

Extends obj1_nlp.py score (unchanged) with:
- a disagreement sheet for adjudication;
- Cohen's kappa and raw agreement for all three labels;
- relevance precision/recall/F1 and a confusion matrix (sample and stratum-weighted);
- food-stress (sentiment) accuracy/precision/recall/F1 of XLM-RoBERTa at 0.5, plus AUC;
- geocoding accuracy and a province confusion matrix.

Reference label: the adjudicated label when `adjudication.csv` is filled; otherwise the items where A and B agree.
NO LABEL IS EVER GENERATED: the script refuses to score until both annotators have filled at least 90% of the items.

    python obj1_annotation_v2.py disagreements   # after A and B are complete -> ../annotation/adjudication.csv
    python obj1_annotation_v2.py score           # -> ../out/obj1_annotation_scores_v2.json
    python obj1_annotation_v2.py selftest        # random labels in a temporary folder; checks the code only, saves nothing
"""
from __future__ import annotations

import sys

sys.dont_write_bytecode = True
sys.stdout.reconfigure(encoding="utf-8")

import json
import tempfile
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parents[1]
ANN, OUT = HERE / "annotation", HERE / "out"
FIELDS = ("food_insecurity_relevant", "province", "food_stress")
PROVINCES = {"Cavite": "PH040100000", "Laguna": "PH040200000", "Batangas": "PH040300000", "Rizal": "PH040400000",
             "Quezon": "PH040500000"}
MIN_FILLED = 0.9


def _load(ann: Path):
    A, B = (pd.read_csv(ann / f"labels_annotator_{x}.csv", dtype=str, encoding="utf-8-sig").fillna("") for x in "AB")
    for d in (A, B):
        for f in FIELDS:
            d[f] = d[f].str.strip()
    filled = lambda d: d["food_insecurity_relevant"].isin(["0", "1"])  # noqa: E731
    if filled(A).mean() < MIN_FILLED or filled(B).mean() < MIN_FILLED:
        raise SystemExit(f"not scored: annotator A filled {int(filled(A).sum())}, B {int(filled(B).sum())} of {len(A)} "
                         f"(each must label at least {MIN_FILLED:.0%}; no label is ever generated by this script)")
    return A, B


def disagreements(ann: Path = ANN):
    A, B = _load(ann)
    m = A.merge(B, on=["item", "article_key", "title"], suffixes=("_A", "_B"))
    diff = np.zeros(len(m), bool)
    for f in FIELDS:
        diff |= (m[f"{f}_A"] != m[f"{f}_B"]).to_numpy()
    d = m[diff][["item", "article_key", "title"] + [f"{f}_{x}" for f in FIELDS for x in "AB"]].copy()
    for f in FIELDS:
        d[f"{f}_adjudicated"] = ""
    d["adjudicator"], d["adjudication_note"] = "", ""
    out = ann / "adjudication.csv"
    if out.exists():
        raise SystemExit(f"{out} exists; it is never overwritten")
    d.to_csv(out, index=False, encoding="utf-8")
    print(f"{len(d)} of {len(m)} items disagree on at least one field -> {out}")


def _kappa(a: pd.Series, b: pd.Series) -> float | None:
    from sklearn.metrics import cohen_kappa_score
    return float(cohen_kappa_score(a, b)) if len(a) and len(set(a) | set(b)) > 1 else None


def _binary(y: np.ndarray, p: np.ndarray, w: np.ndarray | None = None) -> dict:
    w = np.ones(len(y)) if w is None else w
    tp, fp = float(w[(p == 1) & (y == 1)].sum()), float(w[(p == 1) & (y == 0)].sum())
    fn, tn = float(w[(p == 0) & (y == 1)].sum()), float(w[(p == 0) & (y == 0)].sum())
    pr = tp / (tp + fp) if tp + fp else None
    rc = tp / (tp + fn) if tp + fn else None
    return {"n": int(len(y)), "accuracy": (tp + tn) / (tp + tn + fp + fn) if len(y) else None, "precision": pr,
            "recall": rc, "f1": 2 * pr * rc / (pr + rc) if pr and rc else None,
            "confusion": {"TP": round(tp, 2), "FP": round(fp, 2), "FN": round(fn, 2), "TN": round(tn, 2)}}


def score(ann: Path = ANN, out: Path = OUT / "obj1_annotation_scores_v2.json") -> dict:
    from sklearn.metrics import roc_auc_score
    A, B = _load(ann)
    S = pd.read_csv(ann / "system_outputs_SEALED.csv", dtype={"province_code": str, "item": str})
    m = A.merge(B, on="item", suffixes=("_A", "_B")).merge(S, on="item")
    res = {"n_items": int(len(m)), "agreement": {}}
    for f in FIELDS:
        a, b = m[f"{f}_A"], m[f"{f}_B"]
        keep = (a != "") & (b != "") if f != "province" else m["food_insecurity_relevant_A"].isin(["0", "1"])
        res["agreement"][f] = {"n": int(keep.sum()), "raw_agreement": float((a[keep] == b[keep]).mean()) if keep.any() else None,
                               "cohen_kappa": _kappa(a[keep], b[keep])}
    adj = ann / "adjudication.csv"
    ref = {f: m[f"{f}_A"].where(m[f"{f}_A"] == m[f"{f}_B"]) for f in FIELDS}     # agreed items
    res["reference"] = "agreed items only"
    if adj.exists():
        J = pd.read_csv(adj, dtype=str).fillna("")
        done = J[[f"{f}_adjudicated" for f in FIELDS]].ne("").any(axis=1)
        if done.all():
            for f in FIELDS:
                v = J.set_index("item")[f"{f}_adjudicated"]
                ref[f] = ref[f].where(~m["item"].isin(v.index), m["item"].map(v))
            res["reference"] = "agreed items + adjudicated disagreements"
        else:
            res["reference"] = f"agreed items only (adjudication incomplete: {int((~done).sum())} items open)"
    # relevance vs the system's admission (sample and stratum-weighted)
    r = ref["food_insecurity_relevant"]
    k = r.isin(["0", "1"])
    y, p = r[k].astype(int).to_numpy(), m.loc[k, "admitted"].astype(int).to_numpy()
    st = m.loc[k, "stratum"]
    w = (m.loc[k, "stratum_size"].astype(float) / st.map(st.value_counts())).to_numpy()
    res["relevance"] = {"sample": _binary(y, p), "stratum_weighted": _binary(y, p, w)}
    # food stress (sentiment): XLM-RoBERTa score on relevant, admitted items
    fs = ref["food_stress"]
    k = fs.isin(["0", "1"]) & m["xlmr"].notna()
    ys, sc = fs[k].astype(int).to_numpy(), m.loc[k, "xlmr"].astype(float).to_numpy()
    res["food_stress"] = {**_binary(ys, (sc >= .5).astype(int)),
                          "auc": float(roc_auc_score(ys, sc)) if len(set(ys)) == 2 else None}
    # geocoding: the system's province vs the reference province, where the reference names one
    pv = ref["province"].fillna("")
    k = pv.isin(list(PROVINCES))
    sysp = m.loc[k, "province_code"].fillna("none")
    refc = pv[k].map(PROVINCES)
    res["geocoding"] = {"n": int(k.sum()), "accuracy": float((sysp == refc).mean()) if k.any() else None,
                        "confusion": pd.crosstab(refc.rename("reference"), sysp.rename("system")).to_dict()}
    out.write_text(json.dumps(res, indent=1, default=str), encoding="utf-8")
    print(json.dumps(res, indent=1, default=str))
    return res


def selftest():
    """Random labels in a temporary folder exercise every code path. Nothing is written to annotation/ or out/."""
    rng = np.random.default_rng(0)
    with tempfile.TemporaryDirectory() as tmp:
        t = Path(tmp)
        S = pd.read_csv(ANN / "system_outputs_SEALED.csv")
        S.to_csv(t / "system_outputs_SEALED.csv", index=False)
        for x in "AB":
            d = pd.read_csv(ANN / f"labels_annotator_{x}.csv", dtype=str, encoding="utf-8-sig")
            d["food_insecurity_relevant"] = rng.integers(0, 2, len(d)).astype(str)
            d["province"] = rng.choice(list(PROVINCES) + [""], len(d))
            d["food_stress"] = np.where(d["food_insecurity_relevant"] == "1", rng.integers(0, 2, len(d)).astype(str), "")
            d.to_csv(t / f"labels_annotator_{x}.csv", index=False)
        disagreements(t)
        r = score(t, t / "scores.json")
        assert 0 < r["n_items"] == len(S) and r["relevance"]["sample"]["n"] > 0
    print("selftest passed (random labels, temporary folder, nothing saved)")


if __name__ == "__main__":
    {"disagreements": disagreements, "score": score, "selftest": selftest}[sys.argv[1]]()
