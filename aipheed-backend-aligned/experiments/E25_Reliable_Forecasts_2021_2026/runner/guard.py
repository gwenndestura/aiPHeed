ACCESS_LOG: list[dict] = []
_INSTALLED = False
_BYPASS = False


class AccessDenied(PermissionError):
    pass


def _resolve(path) -> Path | None:
    if isinstance(path, int):
        return None
    try:
        return Path(os.fsdecode(path)).resolve()
    except Exception:
        return None


def _under(p: Path, base: Path) -> bool:
    try:
        p.relative_to(base)
        return True
    except ValueError:
        return False


def decide(path, write: bool) -> str:
    p = _resolve(path)
    if p is None:
        return "neutral"
    if _under(p, HOME_CLAUDE):
        return "deny"
    if _under(p, EXP):
        if not write and p in ALLOW:
            return "allow"
        if not write and _under(p, INPUTS) and p.name not in ("PINS.json", "INPUTS_MANIFEST.json"):
            return "deny"                      # inputs are read only through the verified readers
        return "allow"
    if write:
        if _under(p, TEMP) and not _under(p, ROOT):
            return "allow"
        return "deny" if _under(p, ROOT) else "neutral"
    if p in ALLOW:
        return "allow"
    if _under(p, REFERENCE_DIR) and p.suffix.lower() == ".csv":
        return "allow"                         # static PSGC / census reference lists (no outcome data)
    if _under(p, TEMP) and not _under(p, ROOT):
        return "neutral"
    if _under(p, ROOT):
        if _under(p, VENV):
            return "neutral"
        return "deny"
    return "neutral"


def _audit(event: str, args) -> None:
    if _BYPASS:
        return
    if event == "open":
        path, mode = args[0], args[1] if len(args) > 1 else "r"
        flags = args[2] if len(args) > 2 else 0
        write = bool(mode) and any(c in str(mode) for c in "wax+") or bool(
            isinstance(flags, int) and flags & (os.O_WRONLY | os.O_RDWR | os.O_CREAT))
        if decide(path, write) == "deny":
            raise AccessDenied(f"E25 guard: {'write' if write else 'read'} denied: {path}")
    elif event in ("sqlite3.connect", "subprocess.Popen", "os.system", "os.posix_spawn", "os.spawn"):
        raise AccessDenied(f"E25 guard: {event} is blocked")


def sha256_file(p: Path) -> str:
    global _BYPASS
    _BYPASS = True
    try:
        h = hashlib.sha256()
        with open(p, "rb") as f:
            for b in iter(lambda: f.read(1 << 20), b""):
                h.update(b)
        return h.hexdigest()
    finally:
        _BYPASS = False


def verify_allowlist() -> list[dict]:
    out = []
    for p, (want, flt, orig) in sorted(ALLOW.items(), key=lambda kv: str(kv[0])):
        got = sha256_file(p)
        out.append({"read_path": str(p), "original": orig, "sha256_expected": want, "sha256_actual": got,
                    "match": got == want, "authorized_2026_source": p in AUTHORIZED_2026,
                    "read_time_filter": list(flt) if flt else None})
        if got != want:
            raise AccessDenied(f"E25 guard: hash mismatch for {p}")
    return out


def _check(p: Path):
    p = Path(p).resolve()
    if p not in ALLOW:
        raise AccessDenied(f"E25 guard: {p} is not allowlisted")
    want, flt, _ = ALLOW[p]
    if sha256_file(p) != want:
        raise AccessDenied(f"E25 guard: hash mismatch for {p}")
    return want, flt


def read_allowed_text(p: Path) -> str:
    _check(p)
    with open(p, "r", encoding="utf-8", newline="") as f:
        txt = f.read()
    ACCESS_LOG.append({"op": "read_text", "path": str(Path(p).resolve()), "bytes": len(txt.encode("utf-8"))})
    return txt


_ORIG_DATASET = None


def _blocked(name):
    def f(*a, **k):
        raise AccessDenied(f"E25 guard: {name} is blocked; use guard.read_allowed_parquet()")
    return f


def read_allowed_parquet(p: Path, columns: list[str]):
    import pyarrow.dataset as ds
    _, flt = _check(p)
    if flt and flt[0] not in columns:
        columns = list(columns) + [flt[0]]
    dset = _ORIG_DATASET(str(p), format="parquet")
    expr = ((ds.field(flt[0]) >= flt[1]) & (ds.field(flt[0]) <= flt[2])) if flt else None
    df = dset.to_table(columns=list(columns), filter=expr).to_pandas()
    if flt and ((df[flt[0]] < flt[1]) | (df[flt[0]] > flt[2])).any():
        raise AccessDenied(f"E25 guard: filter failed for {p}")
    ACCESS_LOG.append({"op": "read_parquet", "path": str(Path(p).resolve()), "columns": sorted(columns),
                       "row_filter": f"{flt[1]} <= {flt[0]} <= {flt[2]}" if flt else None, "rows_returned": int(len(df))})
    return df


def install() -> None:
    global _INSTALLED, _ORIG_DATASET
    if _INSTALLED:
        return
    import pandas as pd
    import pyarrow.dataset as ds
    import pyarrow.parquet as pq
    _ORIG_DATASET = ds.dataset
    pd.read_parquet = _blocked("pandas.read_parquet")
    for n in ("read_table", "ParquetFile", "ParquetDataset", "read_schema", "read_metadata"):
        setattr(pq, n, _blocked(f"pyarrow.parquet.{n}"))
    ds.dataset = _blocked("pyarrow.dataset.dataset")
    sys.addaudithook(_audit)
    _INSTALLED = True
