"""E25 data-access guard. Import and call install() BEFORE any pandas/pyarrow analysis code.

Allowlist = inputs/PINS.json, generated by runner/materialize_inputs.py from the E17 and E18 guard modules (no
hash is typed anywhere). E18's three 2026 entries carry the user's 2026-10-13 authorization of January-June 2026.
Two more pinned in-window inputs come from inputs/INPUTS_MANIFEST.json (E24v2's 2021-2025 provincial CPI index
file, and the E24/E24v2 prospective seals, which are forecasts, not data).

Policy
  * Data reads only for allowlisted files, SHA-256 re-verified on every read. Parquet only via
    read_allowed_parquet(), which applies the pinned read-time row filter during the scan (rows outside the
    filter are never returned); every other parquet entry point raises.
  * features_fused.parquet also holds 2020 rows; the read-time filter 2021-Q1..2025-Q4 keeps them out of the
    analysis, and e25lib masks the in-window cells that carry 2020 values (lags, accelerations, cpi_dev).
  * The production SWS parquet is read only with its pinned filter 2026-Q1..2026-Q2 (the authorized rounds).
    Its pin was taken when its footer range was 2024-Q3..2026-Q2; a changed file (e.g. a later round added)
    fails the hash check and is never read.
  * Any other open() of a project data file, other experiments, ~/.claude, a database or a model file raises.
  * Writes only inside this experiment folder (and the OS temp dir outside the project, for pytest).
  * sqlite3 and subprocess are blocked.
"""
